/**
 * 각 문자가 무엇인지. 몸통과 눈을 따로 바꾸려면 이것이 있어야 합니다.
 *
 * outline    실루엣 외곽선
 * edge       밝은 모서리 (면과 면 사이, 외곽선 안쪽)
 * faceLit    윗면과 왼쪽면 / 정면의 본체
 * faceEdge   등축 오른쪽면 모서리
 * faceShade  등축 오른쪽면 (그늘) / 정면의 아래·오른쪽 경사
 * bevelLit   정면 위쪽의 밝은 경사
 * pipEdge    눈 테두리 (파인 자국)
 * pipShade   눈 어두운 쪽
 * pipLit     눈 밝은 쪽
 */
export type DiceRole =
  | 'outline'
  | 'edge'
  | 'faceLit'
  | 'faceEdge'
  | 'faceShade'
  | 'bevelLit'
  | 'pipEdge'
  | 'pipShade'
  | 'pipLit'

